// Acceptance criteria as files the coding agent must satisfy: a checklist and a Playwright spec with one test per
// AC id. The spec is a starting point: endpoint checks run as written; screen tests carry a TODO for the real flow.
import { acceptanceItems, projectName, type AcceptanceItem } from "../prompts/compile";
import type { IdeaCard } from "../schema/ideaCard";

const q = (s: string) => JSON.stringify(s);

/** A concrete path for a route pattern: ":id" and "[id]" segments become "1". */
const concrete = (path: string) => path.replace(/:[A-Za-z_]+|\[[^\]]+\]|\{[^}]+\}/g, "1");

function endpointTest(a: AcceptanceItem): string {
  const e = a.endpoint!;
  const url = concrete(e.path);
  const name = q(`${a.id} ${e.method} ${e.path}`);
  if (e.method === "GET") {
    return `  test(${name}, async ({ request }) => {
    const res = await request.get(${q(url)});
    expect(res.status(), "documented response: ${e.response.replace(/[`"\\]/g, "'").slice(0, 120)}").toBeLessThan(400);
  });`;
  }
  const call = e.method.toLowerCase();
  return `  test(${name}, async ({ request }) => {
    // Invalid input must be rejected with a 4xx, never a 5xx.
    const bad = await request.${call}(${q(url)}, { data: { unexpected: true } });
    expect(bad.status()).toBeGreaterThanOrEqual(400);
    expect(bad.status()).toBeLessThan(500);
    // TODO(agent): send a valid ${e.request ? `body (${e.request.replace(/\*\//g, "")})` : "body"} and assert the documented response.
  });`;
}

function screenTest(a: AcceptanceItem): string {
  const s = a.screen!;
  return `  test(${q(`${a.id} Screen "${s.title}"`)}, async ({ page }) => {
    await page.goto("/");
    // TODO(agent): navigate to the "${s.title}" screen, check its loading, empty and error states, and use its primary action.
    await expect(page.getByText(${q(s.title)}, { exact: false }).first()).toBeVisible();
  });`;
}

export function acceptanceSpec(card: IdeaCard): string {
  const items = acceptanceItems(card);
  const body = items.map((a) => (a.kind === "endpoint" ? endpointTest(a) : screenTest(a))).join("\n\n");
  return `// tests/acceptance.spec.ts: generated by TeamMate from the signed plan for ${projectName(card)}.
// One test per acceptance criterion, named by its AC id. Make them pass; do not delete or skip any.
// Run: npx playwright test tests/acceptance.spec.ts (set use.baseURL to your dev server in playwright.config).
import { expect, test } from "@playwright/test";

test.describe("acceptance", () => {
${body || '  test.skip("no criteria", () => {});'}
});
`;
}

export function acceptanceMarkdown(card: IdeaCard): string {
  const items = acceptanceItems(card);
  return `# Acceptance criteria: ${projectName(card)}

Each line is checked by the test of the same id in \`tests/acceptance.spec.ts\`.

${items.length ? items.map((a) => `- [ ] **${a.id}** ${a.text}`).join("\n") : "_No criteria yet: generate a preview and an API surface._"}

## Build report format

When the build is done, report one line per criterion, then the test summary:

\`\`\`
${items.slice(0, 2).map((a, i) => (i === 0 ? `${a.id} PASS` : `${a.id} FAIL — reason`)).join("\n") || "AC-01 PASS"}
\`\`\`

Paste the report into TeamMate's **Verify** stage. It marks each criterion and writes the next prompt for the failures.
`;
}
