import React, { useState } from 'react';
import type { PlanReviewResult } from '../../../../shared/plan-review';
import type { VisualArchetype } from './VisualArchetypes';
import type { IdeaReport } from '../../../../shared/idea-report';
import { voiceDispatcher } from '../../utils/speech';

export type ToolTarget = 'cursor' | 'copilot' | 'windsurf' | 'gemini' | 'markdown';

interface PromptGeneratorProps {
  idea: string;
  report: IdeaReport | null;
  archetype: VisualArchetype;
  techStack: {
    framework: string;
    styling: string;
    database: string;
    stateManagement: string;
  };
  features: { id: string; title: string; priority: 'P0' | 'P1' | 'P2'; selected: boolean }[];
  constraints: string[];
  nonGoals: string[];
  decisions: { question: string; answer: string }[];
  /** The council's latest review of exactly this plan, if any. */
  council?: PlanReviewResult | null;
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'color';

export function buildPromptText({
  target,
  idea,
  report,
  archetype,
  techStack,
  features,
  constraints,
  nonGoals,
  decisions,
  council,
}: PromptGeneratorProps & { target: ToolTarget }): string {
  const selectedFeatures = features.filter((f) => f.selected);
  const p0 = selectedFeatures.filter((f) => f.priority === 'P0');
  const p1 = selectedFeatures.filter((f) => f.priority === 'P1');
  const p2 = selectedFeatures.filter((f) => f.priority === 'P2');

  const header = {
    cursor: `# .cursorrules / Claude 3.7 Sonnet System Specification`,
    copilot: `# GitHub Copilot Workspace Directive`,
    windsurf: `# Windsurf Cascade / Bolt AI Implementation Blueprint`,
    gemini: `# Gemini 2.5 Pro Application Generation Context`,
    markdown: `# Project Specification & AI Implementation Blueprint`,
  }[target];

  return `${header}
Generated by TEAM:MATE — The Human Has the Key
Date: ${new Date().toISOString().split('T')[0]}

## 1. PROJECT OBJECTIVE & PROBLEM STATEMENT
Objective: ${idea}
Feasibility Score: ${report ? `${report.overallScore}/100 (${report.verdict} verdict)` : 'not assessed'}
Target Audience: Hackathon judges, technical developers, and end-users.

## 2. TECHNICAL ARCHITECTURE & STACK
- Frontend Framework: ${techStack.framework}
- Styling System: ${techStack.styling}
- Data Storage / Persistence: ${techStack.database}
- State & Reactivity: ${techStack.stateManagement}

## 3. VISUAL CONSTITUTION & DESIGN TOKENS
Archetype Selected: ${archetype.name}
Tagline: ${archetype.tagline}

Design Tokens (Inject into root stylesheet):
${archetype.id === 'custom' ? `:root {\n${archetype.palette.map((c) => `  --${slug(c.name)}: ${c.hex};`).join('\n')}\n}` : archetype.sampleCssVars}

Typography Pairings:
- Display / Headlines: ${archetype.typography.display}
- Body Text: ${archetype.typography.body}
- Numerals & Telemetry: ${archetype.typography.data} (always tabular-nums)

Mandatory Anti-Slop Rules:
${archetype.principles.map((p) => `- ${p}`).join('\n')}
- No pill-badge sandwiches on cards; render metadata as clean unboxed text with subtle separators (· or /).
- No fake execution tickers, mock compiler flags, or arbitrary single-number scorecards.
- Minimum 44x44px touch targets on all interactive controls.
- Provide loading skeletons (never spinning donuts) and clear empty states.

## 4. HUMAN DECISIONS & SPECIFICATION CHOICES
${decisions.map((d) => `- Decision: ${d.question}\n  Resolved As: ${d.answer}`).join('\n\n')}

Constraints (always apply):
${constraints.length ? constraints.map((c) => `- ${c}`).join('\n') : '- None recorded'}

## 5. FEATURE SPECIFICATION & PRIORITIES

### Must-Have Core (P0):
${p0.map((f) => `- [ ] ${f.title}`).join('\n')}

### Secondary Enhancements (P1):
${p1.length > 0 ? p1.map((f) => `- [ ] ${f.title}`).join('\n') : '- [ ] None specified'}

### Stretch Polish (P2):
${p2.length > 0 ? p2.map((f) => `- [ ] ${f.title}`).join('\n') : '- [ ] None specified'}

## 6. EXPLICIT NON-GOALS (DO NOT IMPLEMENT)
${nonGoals.map((ng) => `- DO NOT BUILD: ${ng}`).join('\n')}

${council ? `## COUNCIL REVIEW (before human approval)
Verdict: ${council.verdict} · Solidity ${council.solidity}/100 · ${council.method === 'council' ? 'AI agent council' : 'rule-based checks, no model'}
${council.summary}

Attacks the plan must survive:
${council.breakAttempts.map((b) => `- [${b.holds ? 'HOLDS' : 'OPEN'} · ${b.severity}] ${b.attack} -> ${b.mitigation}`).join('\n') || '- None recorded'}
${council.requiredChanges.length ? `\nChanges the council asked for:\n${council.requiredChanges.map((c) => `- ${c}`).join('\n')}\n` : ''}
` : ''}## 7. RECOMMENDED IMPLEMENTATION SEQUENCE
1. Setup scaffolding with ${techStack.framework} and ${techStack.styling}.
2. Configure the design tokens and typography pairings in CSS variables.
3. Implement core domain state models and mock data repositories.
4. Construct layout shell with top navigation bar and responsive container.
5. Build P0 feature components with loading, empty, and populated states.
6. Verify WCAG AA contrast (4.5:1 text, 3:1 large), keyboard focus-visible rings, and mobile viewport ergonomics.
7. Run build verification and manual functional testing.
`;
}

export function PromptGenerator(props: PromptGeneratorProps) {
  const [target, setTarget] = useState<ToolTarget>('cursor');
  const [copied, setCopied] = useState(false);
  /** The leader's own version of the prompt; null means use the generated one. */
  const [custom, setCustom] = useState<string | null>(null);
  const [editing, setEditing] = useState(false);

  const generated = buildPromptText({ ...props, target });
  const promptContent = custom ?? generated;

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(promptContent);
      setCopied(true);
      setTimeout(() => setCopied(false), 2500);
    } catch {
      // Fallback
    }
  };

  const handleDownload = () => {
    const blob = new Blob([promptContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `teammate-prompt-${target}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-4">
      {/* Target Tool Selector Tabs with five-state interaction */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-[var(--line)] pb-4">
        <div>
          <h3 className="text-sm font-bold text-[var(--text)]">
            AI Coding Tool Export Target
          </h3>
          <p className="text-xs text-[var(--text-dim)] mt-0.5">
            Optimized instruction structure for your external agent or IDE
          </p>
        </div>

        <div className="flex items-center gap-2 p-1 bg-[var(--panel)] rounded-lg border border-[var(--line)] overflow-x-auto">
          {[
            { id: 'cursor', label: 'Claude / Cursor' },
            { id: 'copilot', label: 'GitHub Copilot' },
            { id: 'windsurf', label: 'Windsurf / Bolt' },
            { id: 'gemini', label: 'Gemini 2.5' },
            { id: 'markdown', label: 'Raw Markdown' },
          ].map((t) => {
            const isSelected = target === t.id;
            return (
              <button
                key={t.id}
                type="button"
                onClick={() => setTarget(t.id as ToolTarget)}
                aria-pressed={isSelected}
                className={`min-h-[44px] px-3.5 py-2 text-xs font-mono uppercase rounded transition-colors duration-150 whitespace-nowrap active:scale-[0.98] focus-visible:ring-2 focus-visible:ring-offset-2 focus-visible:ring-[var(--focus)] focus-visible:ring-offset-[var(--glass)] ${
                  isSelected
                    ? 'bg-[var(--glass)] text-[var(--brand)] font-bold border border-[var(--brand)]/50'
                    : 'text-[var(--text-dim)] hover:text-[var(--text)] hover:bg-[var(--glass)]'
                }`}
              >
                {t.label}
              </button>
            );
          })}
        </div>
      </div>

      {/* 3A.8 Sticky Action Bar at z-20 */}
      <div className="sticky top-16 z-20 flex items-center justify-between gap-4 bg-[var(--panel)] p-4 rounded-xl border border-[var(--line)] shadow-lg backdrop-blur-md">
        <div className="flex items-center gap-2 text-xs font-mono text-[var(--text-dim)]">
          <span className="w-2 h-2 rounded-full bg-[var(--ok)] shrink-0" aria-hidden="true" />
          <span className="tabular-nums">Blueprint formatted ({promptContent.split('\n').length} lines)</span>
        </div>

        <div className="flex items-center gap-2">
          {/* Read Aloud Button */}
          <button
            type="button"
            onClick={() => {
              const summary = `Generated prompt specification for ${props.idea}. Target: ${target}. Includes ${props.features.filter((f) => f.selected).length} approved features, ${props.archetype.name} visual design tokens, and explicit non-goals. Ready for external AI build.`;
              voiceDispatcher.speak(summary);
            }}
            aria-label="Read architectural summary audibly"
            className="min-h-[44px] px-3.5 py-2 rounded-lg border border-[var(--line)] bg-[var(--panel)] hover:border-[var(--brand)] text-[var(--brand)] text-xs font-mono uppercase transition-all duration-150 flex items-center gap-1.5 focus-visible:ring-2 focus-visible:ring-offset-2 focus-visible:ring-[var(--focus)] focus-visible:ring-offset-[var(--glass)]"
          >
            <svg className="w-3.5 h-3.5 fill-none stroke-current stroke-2 shrink-0" viewBox="0 0 24 24" aria-hidden="true">
              <polygon points="11 5 6 9 2 9 2 15 6 15 11 19 11 5" />
              <path d="M19.07 4.93a10 10 0 0 1 0 14.14M15.54 8.46a5 5 0 0 1 0 7.07" />
            </svg>
            <span className="hidden sm:inline">READ ALOUD</span>
          </button>

          {/* Secondary Button */}
          <button
            type="button"
            onClick={handleDownload}
            aria-label="Download prompt as markdown file"
            className="min-h-[44px] px-4 py-2 rounded-lg border border-[var(--line)] bg-[var(--panel)] hover:border-[var(--text-dim)] hover:bg-[var(--glass)] active:scale-[0.98] text-[var(--text)] text-xs font-mono uppercase transition-all duration-150 focus-visible:ring-2 focus-visible:ring-offset-2 focus-visible:ring-[var(--focus)] focus-visible:ring-offset-[var(--glass)]"
          >
            DOWNLOAD .MD
          </button>

          {/* Primary Button */}
          <button
            type="button"
            onClick={handleCopy}
            aria-label={copied ? 'Prompt copied to clipboard' : 'Copy prompt specification to clipboard'}
            className="min-h-[44px] px-5 py-2 rounded-lg bg-[var(--brand)] text-[#101010] [data-theme='light']_:text-white font-mono font-bold text-xs uppercase hover:brightness-110 active:scale-[0.98] transition-all duration-150 flex items-center gap-2 shadow-[0_0_12px_var(--amber-glow)] focus-visible:ring-2 focus-visible:ring-offset-2 focus-visible:ring-[var(--focus)] focus-visible:ring-offset-[var(--glass)]"
          >
            {copied ? (
              <>
                <svg className="w-4 h-4 fill-current" viewBox="0 0 16 16" aria-hidden="true">
                  <path d="M6 11.5L2.5 8l1.4-1.4L6 8.7l6.1-6.2L13.5 4z" />
                </svg>
                <span>COPIED!</span>
              </>
            ) : (
              <>
                <svg className="w-4 h-4 fill-none stroke-current stroke-2" viewBox="0 0 24 24" aria-hidden="true">
                  <rect x="9" y="9" width="13" height="13" rx="2" ry="2" />
                  <path d="M5 15H4a2 2 0 0 1-2-2V4a2 2 0 0 1 2-2h9a2 2 0 0 1 2 2v1" />
                </svg>
                <span>COPY PROMPT</span>
              </>
            )}
          </button>
        </div>
      </div>

      <div className="flex flex-wrap items-center justify-between gap-2">
        <span className="text-xs font-mono text-[var(--text-dim)]">
          {custom !== null ? 'Your edited prompt. Switching tool target keeps your edits.' : 'Generated from your approved plan.'}
        </span>
        <div className="flex gap-2">
          {custom !== null && (
            <button type="button" onClick={() => { setCustom(null); setEditing(false); }}
              className="min-h-[40px] px-3.5 py-2 rounded-lg border border-[var(--line)] text-xs font-mono uppercase text-[var(--text-dim)] hover:text-[var(--text)]">
              Reset to generated
            </button>
          )}
          <button type="button" aria-expanded={editing} data-testid="edit-prompt"
            onClick={() => { if (!editing && custom === null) setCustom(generated); setEditing((e) => !e); }}
            className={`min-h-[40px] px-3.5 py-2 rounded-lg border text-xs font-mono uppercase ${editing ? 'border-[var(--info)] text-[var(--info)] bg-[var(--info)]/10' : 'border-[var(--line)] text-[var(--text-dim)] hover:text-[var(--text)]'}`}>
            ✎ {editing ? 'Done editing' : 'Edit prompt'}
          </button>
        </div>
      </div>

      {/* Structured Code Display with 3A.4 Typography (16/28 line-height) */}
      <div className="rounded-xl border border-[var(--line)] bg-[var(--glass)] p-4 sm:p-6 overflow-hidden">
        {editing ? (
          <textarea aria-label="Edit the prompt" value={promptContent} onChange={(e) => setCustom(e.target.value)} rows={22}
            className="w-full bg-transparent text-sm font-mono leading-7 text-[var(--text)] focus:outline-none resize-y" />
        ) : (
          <pre className="text-sm sm:text-base font-mono leading-7 text-[var(--text)] whitespace-pre-wrap max-h-[520px] overflow-y-auto select-all" data-testid="prompt-text">
            {promptContent}
          </pre>
        )}
      </div>
    </div>
  );
}
